import streamlit as st

from app.llm.sql_generator import generate_sql
from app.services.sql_validator import validate_sql
from app.services.query_executor import execute_sql
from app.services.query_history import save_query_history


def render_sql_assistant():

    st.title("🤖 AI SQL Assistant")

    st.caption(
        "Transform natural-language questions into "
        "PostgreSQL queries using Groq AI."
    )

    st.divider()

    st.subheader("Ask Your Database")

    example_questions = [
        "Show me the top 3 restaurants by average customer rating.",
        "List all restaurants located in Coimbatore.",
        "Find the total revenue generated by each restaurant.",
        "Show customers who have placed more than one order.",
        "Find the most popular menu items based on quantity sold."
    ]

    selected_example = st.selectbox(
        "Try an example question",
        ["Choose an example..."] + example_questions
    )

    default_question = (
        selected_example
        if selected_example != "Choose an example..."
        else ""
    )

    question = st.text_area(
        "Enter your question",
        value=default_question,
        placeholder="Ask anything about your database...",
        height=120
    )

    if st.button(
        "✨ Generate SQL",
        type="primary",
        use_container_width=True
    ):

        if not question.strip():

            st.warning("Please enter a question.")

        else:

            with st.spinner("Groq is generating your SQL..."):

                try:

                    sql_query = generate_sql(question)

                    st.session_state["generated_sql"] = sql_query
                    st.session_state["last_question"] = question

                    # Remove previous execution results
                    st.session_state.pop("query_result", None)

                    st.success("SQL generated successfully!")

                except Exception as error:

                    st.error(f"SQL generation failed: {error}")

    # Display generated SQL
    if st.session_state.get("generated_sql"):

        sql_query = st.session_state["generated_sql"]

        st.divider()

        st.subheader("Generated SQL Query")

        st.caption(
            f"Question: {st.session_state.get('last_question', '')}"
        )

        st.code(sql_query, language="sql")

        st.download_button(
            "⬇️ Download SQL",
            data=sql_query,
            file_name="sqlgenpro_query.sql",
            mime="text/plain",
            use_container_width=True
        )

        # Validate SQL
        st.subheader("🛡️ SQL Safety Validation")

        validation = validate_sql(sql_query)

        if validation["valid"]:

            st.success(validation["message"])

            if st.button(
                "▶ Execute SQL Query",
                type="primary",
                use_container_width=True
            ):

                with st.spinner(
                    "Executing query against PostgreSQL..."
                ):

                    try:

                        result = execute_sql(sql_query)

                        st.session_state["query_result"] = result

                        # Save successful execution to PostgreSQL history
                        try:

                            save_query_history(
                                user_question=st.session_state.get(
                                    "last_question", ""
                                ),
                                generated_sql=sql_query,
                                execution_time=result["execution_time"],
                                rows_returned=result["row_count"]
                            )

                            st.success(
                                "Query executed successfully and saved to history!"
                            )

                        except Exception as history_error:

                            st.warning(
                                "Query executed successfully, but history "
                                f"could not be saved: {history_error}"
                            )

                    except Exception as error:

                        st.session_state.pop(
                            "query_result", None
                        )

                        st.error(str(error))

        else:

            st.error(
                f"Query rejected: {validation['message']}"
            )

    # Display execution results
    if st.session_state.get("query_result"):

        result = st.session_state["query_result"]

        st.divider()

        st.subheader("📊 Query Results")

        col1, col2, col3 = st.columns(3)

        col1.metric(
            "Rows Returned",
            result["row_count"]
        )

        col2.metric(
            "Execution Time",
            f"{result['execution_time']} sec"
        )

        col3.metric(
            "Result Status",
            "Truncated" if result["truncated"] else "Complete"
        )

        st.dataframe(
            result["data"],
            use_container_width=True,
            hide_index=True
        )

        if result["truncated"]:

            st.warning(
                f"Showing the first {result['row_count']} rows. "
                "Additional rows were excluded from the preview."
            )

        # Download query results
        csv_data = result["data"].to_csv(index=False)

        st.download_button(
            "⬇️ Download Results as CSV",
            data=csv_data,
            file_name="sqlgenpro_results.csv",
            mime="text/csv",
            use_container_width=True
        )
